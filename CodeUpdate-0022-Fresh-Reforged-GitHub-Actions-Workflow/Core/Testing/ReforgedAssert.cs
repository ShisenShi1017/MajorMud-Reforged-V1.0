namespace Reforged.Core.Testing;

/// <summary>
/// Minimal dependency-free assertion helpers for early Core tests.
/// These helpers are source-level test infrastructure and do not create a runtime SDK requirement.
/// </summary>
public static class ReforgedAssert
{
    public static void True(bool condition, string message)
    {
        if (!condition)
        {
            throw new InvalidOperationException(message);
        }
    }

    public static void Equal<T>(T expected, T actual, string message)
    {
        if (!EqualityComparer<T>.Default.Equals(expected, actual))
        {
            throw new InvalidOperationException($"{message} Expected: {expected}; Actual: {actual}");
        }
    }

    public static void NotNull(object? value, string message)
    {
        if (value is null)
        {
            throw new InvalidOperationException(message);
        }
    }
}
