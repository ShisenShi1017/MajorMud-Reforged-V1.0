param(
    [string]$RepoRoot = ""
)

$ErrorActionPreference = "Stop"

if ([string]::IsNullOrWhiteSpace($RepoRoot)) {
    $RepoRoot = Split-Path -Parent $PSScriptRoot
}
$RepoRoot = [System.IO.Path]::GetFullPath($RepoRoot)
$ProjectRoot = Join-Path $RepoRoot "Apps\Source\Reforged.App"

if (-not (Test-Path -LiteralPath $ProjectRoot)) {
    throw "Reforged.App project was not found at: $ProjectRoot"
}

$canonical = @(
    (Join-Path $ProjectRoot "App.xaml"),
    (Join-Path $ProjectRoot "App.xaml.cs"),
    (Join-Path $ProjectRoot "MainWindow.xaml"),
    (Join-Path $ProjectRoot "MainWindow.xaml.cs")
) | ForEach-Object { [System.IO.Path]::GetFullPath($_) }

$stamp = Get-Date -Format "yyyyMMdd-HHmmss"
$quarantineRoot = Join-Path $RepoRoot ("_UpdateQuarantine\ReforgedApp-Duplicates-" + $stamp)
$moved = New-Object System.Collections.Generic.List[string]

function Is-Canonical([string]$Path) {
    $full = [System.IO.Path]::GetFullPath($Path)
    foreach ($item in $canonical) {
        if ([string]::Equals($full, $item, [System.StringComparison]::OrdinalIgnoreCase)) {
            return $true
        }
    }
    return $false
}

function Should-Quarantine([System.IO.FileInfo]$File) {
    if (Is-Canonical $File.FullName) { return $false }

    $segments = $File.FullName.Split([System.IO.Path]::DirectorySeparatorChar)
    if ($segments -contains "bin" -or $segments -contains "obj") { return $false }

    if ($File.Extension -ieq ".xaml") {
        $text = Get-Content -LiteralPath $File.FullName -Raw -ErrorAction SilentlyContinue
        if ($null -eq $text) { return $false }
        return ($text -match 'x:Class\s*=\s*"Reforged\.App\.(App|MainWindow)"')
    }

    if ($File.Extension -ieq ".cs") {
        $text = Get-Content -LiteralPath $File.FullName -Raw -ErrorAction SilentlyContinue
        if ($null -eq $text) { return $false }
        $namespaceMatch = ($text -match 'namespace\s+Reforged\.App(?:\s*;|\s*\{)')
        $classMatch = ($text -match '\bpartial\s+class\s+(App|MainWindow)\b')
        return ($namespaceMatch -and $classMatch)
    }

    return $false
}

Write-Host "Scanning $ProjectRoot for duplicate WPF App/MainWindow source..."
$files = Get-ChildItem -LiteralPath $ProjectRoot -Recurse -File -ErrorAction Stop |
    Where-Object { $_.Extension -ieq ".cs" -or $_.Extension -ieq ".xaml" }

foreach ($file in $files) {
    if (-not (Should-Quarantine $file)) { continue }

    $relative = $file.FullName.Substring($RepoRoot.Length).TrimStart('\','/')
    $destination = Join-Path $quarantineRoot $relative
    $destDir = Split-Path -Parent $destination
    New-Item -ItemType Directory -Force -Path $destDir | Out-Null

    if (Test-Path -LiteralPath $destination) {
        $destination = $destination + "." + [Guid]::NewGuid().ToString("N")
    }

    Move-Item -LiteralPath $file.FullName -Destination $destination -Force
    $moved.Add($relative)
    Write-Host "Quarantined duplicate: $relative"
}

# Remove stale WPF-generated files. These are regenerated by the next build.
foreach ($dirName in @("bin", "obj")) {
    $path = Join-Path $ProjectRoot $dirName
    if (Test-Path -LiteralPath $path) {
        Write-Host "Removing stale $dirName output: $path"
        Remove-Item -LiteralPath $path -Recurse -Force
    }
}

# Verify the four canonical files are present after cleanup.
foreach ($path in $canonical) {
    if (-not (Test-Path -LiteralPath $path)) {
        throw "Canonical WPF source is missing after cleanup: $path"
    }
}

Write-Host ""
if ($moved.Count -eq 0) {
    Write-Host "No extra App/MainWindow definitions were found outside bin/obj. Stale generated files were still cleared."
} else {
    Write-Host ("Quarantined {0} duplicate source/XAML file(s) to: {1}" -f $moved.Count, $quarantineRoot)
}
Write-Host "Reforged.App cleanup complete."
